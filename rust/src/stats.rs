//! Opt-in search statistics, enabled with `cargo build --features stats`.
//!
//! Without the feature every recording function is an empty `#[inline(always)]` function,
//! so the solver pays nothing for the calls left in the hot path.
//!
//! With the feature, each thread increments its own counter array (registered once in a
//! global list), so there is no contention between threads: only the owning thread ever
//! writes its counters, using plain relaxed load + store instead of an atomic RMW. A
//! [`snapshot`] sums all threads; taken while threads are running it may be a few
//! increments behind, which is fine for statistics.
//!
//! Counters are bucketed by the size (number of segments) of the state they relate to.

use serde_json::{json, Map, Value};

/// Whether the crate was built with `--features stats`.
pub const ENABLED: bool = cfg!(feature = "stats");

/// Counters are kept per state size `0..SIZE_BUCKETS`; larger sizes land in the last bucket.
/// States hold at most 28 events = 14 segments.
pub const SIZE_BUCKETS: usize = 16;

/// Who asked for a state-map lookup.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Caller {
    /// The iterative-deepening root.
    Root = 0,
    /// A colour branch of an insert move.
    Move = 1,
    /// The front reduction of a state.
    ReductionFront = 2,
    /// The back reduction of a state.
    ReductionBack = 3,
}

/// Outcome of a state-map lookup in `find_strategy_inner`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lookup {
    /// A winning entry applies: the state is won without searching.
    Winning = 0,
    /// A losing entry searched at least as deep applies: lost without searching.
    LosingDeep = 1,
    /// Only a shallower losing entry applies: the state is searched again.
    LosingShallow = 2,
    /// The state is being searched (by an ancestor or another thread): treated as losing.
    InProgress = 3,
    /// Nothing applies: the state is searched.
    Unknown = 4,
}

const LOOKUP_OUTCOMES: usize = 5;

macro_rules! counters {
    ($($name:ident),* $(,)?) => {
        /// Everything that is counted. Names are used as-is in the JSON output.
        #[allow(non_camel_case_types)]
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        #[repr(usize)]
        pub enum Counter { $($name),* }

        impl Counter {
            pub const ALL: &'static [Counter] = &[$(Counter::$name),*];
            pub const COUNT: usize = Self::ALL.len();
            pub fn name(self) -> &'static str {
                match self { $(Counter::$name => stringify!($name)),* }
            }
        }
    };
}

counters!(
    // Lookups: `Caller` x `Lookup`, in exactly this order (see `lookup_counter`).
    lookup_root_win,
    lookup_root_lose_deep,
    lookup_root_lose_shallow,
    lookup_root_in_progress,
    lookup_root_unknown,
    lookup_move_win,
    lookup_move_lose_deep,
    lookup_move_lose_shallow,
    lookup_move_in_progress,
    lookup_move_unknown,
    lookup_front_win,
    lookup_front_lose_deep,
    lookup_front_lose_shallow,
    lookup_front_in_progress,
    lookup_front_unknown,
    lookup_back_win,
    lookup_back_lose_deep,
    lookup_back_lose_shallow,
    lookup_back_in_progress,
    lookup_back_unknown,
    // A searched state reached depth 0.
    depth_zero,
    // A searched state checked its reductions (every searched state with depth > 0).
    reduction_check,
    // A reduction check found a win through the front / back reduction.
    reduction_win_front,
    reduction_win_back,
    // A state at the size limit lost (no reduction wins, no insert moves allowed).
    at_limit_lose,
    // A state below the size limit tried its insert moves.
    expansion,
    // Number of insert moves generated by expansions.
    moves_generated,
    // An expansion found a winning move / found none.
    expansion_win,
    expansion_lose,
    // An insert move was evaluated (bucketed by the size of the state before the insert).
    move_tried,
    // A colour answer to an insert move was searched.
    colour_branch,
    // A move lost because some colour answer was not winning.
    move_refuted,
    // `update_status` calls (writes to the state map).
    status_write,
);

/// The lookup counter for a caller and outcome.
#[inline(always)]
pub fn lookup_counter(caller: Caller, outcome: Lookup) -> Counter {
    Counter::ALL[caller as usize * LOOKUP_OUTCOMES + outcome as usize]
}

/// Record one event for a state of `size` segments.
#[inline(always)]
pub fn inc(counter: Counter, size: u8) {
    imp::add(counter, size, 1);
}

/// Record `n` events for a state of `size` segments.
#[inline(always)]
pub fn add(counter: Counter, size: u8, n: u64) {
    imp::add(counter, size, n);
}

/// Record a state-map lookup.
#[inline(always)]
pub fn lookup(caller: Caller, outcome: Lookup, size: u8) {
    imp::add(lookup_counter(caller, outcome), size, 1);
}

/// Current totals over all threads (all zeros when the feature is off).
pub fn snapshot() -> Snapshot {
    imp::snapshot()
}

const SLOTS: usize = Counter::COUNT * SIZE_BUCKETS;

#[inline(always)]
fn slot(counter: Counter, size: u8) -> usize {
    counter as usize * SIZE_BUCKETS + (size as usize).min(SIZE_BUCKETS - 1)
}

#[cfg(feature = "stats")]
mod imp {
    use super::*;
    use std::sync::{
        atomic::{AtomicU64, Ordering::Relaxed},
        Mutex,
    };

    // Aligned so different threads' counters never share a cache line.
    #[repr(align(128))]
    struct ThreadCounters([AtomicU64; SLOTS]);

    static REGISTRY: Mutex<Vec<&'static ThreadCounters>> = Mutex::new(Vec::new());

    thread_local! {
        // Leaked on purpose: totals must survive the thread so snapshots stay complete.
        static LOCAL: &'static ThreadCounters = {
            let counters: &'static ThreadCounters = Box::leak(Box::new(ThreadCounters(
                std::array::from_fn(|_| AtomicU64::new(0)),
            )));
            REGISTRY.lock().unwrap().push(counters);
            counters
        };
    }

    #[inline(always)]
    pub fn add(counter: Counter, size: u8, n: u64) {
        LOCAL.with(|counters| {
            // Only this thread writes this slot, so load + store cannot lose updates.
            let slot = &counters.0[slot(counter, size)];
            slot.store(slot.load(Relaxed) + n, Relaxed);
        });
    }

    pub fn snapshot() -> Snapshot {
        let mut counts = vec![0u64; SLOTS];
        for counters in REGISTRY.lock().unwrap().iter() {
            for (total, slot) in counts.iter_mut().zip(counters.0.iter()) {
                *total += slot.load(Relaxed);
            }
        }
        Snapshot { counts }
    }
}

#[cfg(not(feature = "stats"))]
mod imp {
    use super::*;

    #[inline(always)]
    pub fn add(_counter: Counter, _size: u8, _n: u64) {}

    pub fn snapshot() -> Snapshot {
        Snapshot::default()
    }
}

/// Counter totals at one moment (or, after [`Snapshot::since`], over an interval).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Snapshot {
    counts: Vec<u64>,
}

impl Default for Snapshot {
    fn default() -> Self {
        Self {
            counts: vec![0; SLOTS],
        }
    }
}

impl Snapshot {
    /// Counts per state size.
    pub fn by_size(&self, counter: Counter) -> &[u64] {
        let start = slot(counter, 0);
        &self.counts[start..start + SIZE_BUCKETS]
    }

    pub fn total(&self, counter: Counter) -> u64 {
        self.by_size(counter).iter().sum()
    }

    /// All lookups made by `caller`.
    pub fn lookups(&self, caller: Caller) -> u64 {
        (0..LOOKUP_OUTCOMES)
            .map(|o| self.total(Counter::ALL[caller as usize * LOOKUP_OUTCOMES + o]))
            .sum()
    }

    /// Total of one lookup outcome over all callers.
    pub fn outcome(&self, outcome: Lookup) -> u64 {
        [
            Caller::Root,
            Caller::Move,
            Caller::ReductionFront,
            Caller::ReductionBack,
        ]
        .into_iter()
        .map(|c| self.total(lookup_counter(c, outcome)))
        .sum()
    }

    /// The counts accumulated since `earlier`.
    pub fn since(&self, earlier: &Snapshot) -> Snapshot {
        Snapshot {
            counts: self
                .counts
                .iter()
                .zip(&earlier.counts)
                .map(|(now, before)| now.saturating_sub(*before))
                .collect(),
        }
    }

    /// `{ "<counter>": { "total": n, "by_size": [..] }, .. }`
    pub fn to_json(&self) -> Value {
        let mut map = Map::new();
        for &counter in Counter::ALL {
            map.insert(
                counter.name().to_string(),
                json!({ "total": self.total(counter), "by_size": self.by_size(counter) }),
            );
        }
        Value::Object(map)
    }

    /// One-line human summary used by the per-depth console output.
    pub fn summary_line(&self) -> String {
        let pct = |part: u64, whole: u64| {
            if whole == 0 {
                "-".to_string()
            } else {
                format!("{:.1}%", 100.0 * part as f64 / whole as f64)
            }
        };
        let unknown = |caller| {
            pct(
                self.total(lookup_counter(caller, Lookup::Unknown)),
                self.lookups(caller),
            )
        };
        let lookups: u64 = [
            Caller::Root,
            Caller::Move,
            Caller::ReductionFront,
            Caller::ReductionBack,
        ]
        .into_iter()
        .map(|c| self.lookups(c))
        .sum();
        format!(
            "lookups {}  searched {}  expansions {}  colour branches {}  re-searched (shallow) {}  in-progress hits {}  unknown: move {} front {} back {}",
            lookups,
            self.total(Counter::reduction_check) + self.total(Counter::depth_zero),
            self.total(Counter::expansion),
            self.total(Counter::colour_branch),
            self.outcome(Lookup::LosingShallow),
            self.outcome(Lookup::InProgress),
            unknown(Caller::Move),
            unknown(Caller::ReductionFront),
            unknown(Caller::ReductionBack),
        )
    }
}

#[cfg(test)]
mod test {
    use super::*;

    #[test]
    fn lookup_counters_match_names() {
        let callers = [
            (Caller::Root, "root"),
            (Caller::Move, "move"),
            (Caller::ReductionFront, "front"),
            (Caller::ReductionBack, "back"),
        ];
        let outcomes = [
            (Lookup::Winning, "win"),
            (Lookup::LosingDeep, "lose_deep"),
            (Lookup::LosingShallow, "lose_shallow"),
            (Lookup::InProgress, "in_progress"),
            (Lookup::Unknown, "unknown"),
        ];
        for (caller, c) in callers {
            for (outcome, o) in outcomes {
                assert_eq!(
                    lookup_counter(caller, outcome).name(),
                    format!("lookup_{c}_{o}")
                );
            }
        }
    }

    #[test]
    fn counter_names_unique() {
        let mut names: Vec<_> = Counter::ALL.iter().map(|c| c.name()).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), Counter::COUNT);
    }

    #[test]
    fn snapshot_since_and_json() {
        let mut later = Snapshot::default();
        later.counts[slot(Counter::expansion, 3)] = 5;
        later.counts[slot(Counter::expansion, 200)] = 2; // clamps to the last bucket
        let delta = later.since(&Snapshot::default());
        assert_eq!(delta.total(Counter::expansion), 7);
        assert_eq!(delta.by_size(Counter::expansion)[3], 5);
        assert_eq!(delta.by_size(Counter::expansion)[SIZE_BUCKETS - 1], 2);
        assert_eq!(delta.to_json()["expansion"]["total"], 7);
        assert_eq!(Snapshot::default().since(&later), Snapshot::default());
    }
}
